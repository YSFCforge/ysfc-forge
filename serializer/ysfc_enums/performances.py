def get_performance_name(perf_no):
    entry = PERFORMANCES.get(perf_no)
    return entry[0] if entry else f'Unknown({perf_no})'


def get_performance(perf_no):
    entry = PERFORMANCES.get(perf_no)
    if entry is None: return None
    return {'name': entry[0], 'main_cat': entry[1], 'sub_cat': entry[2]}


def perfs_by_category(main_cat=None, sub_cat=None):
    result = []
    for k, (name, mc, sc) in PERFORMANCES.items():
        if main_cat and mc != main_cat: continue
        if sub_cat and sc != sub_cat: continue
        result.append((k, name))
    return sorted(result)


