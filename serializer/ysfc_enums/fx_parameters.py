def get_parameters(fx_name):
    """Returns list of parameter dicts for an FX type."""
    return FX_PARAMETERS.get(fx_name, [])


def get_parameter(fx_name, param_no):
    """Returns single parameter dict by number (1-based)."""
    params = FX_PARAMETERS.get(fx_name, [])
    for p in params:
        if p['no'] == param_no:
            return p
    return None


def get_table_no(fx_name, param_no):
    """Returns table number för parameter-konvertering (or empty string)."""
    p = get_parameter(fx_name, param_no)
    if p and p['table_no']:
        try:
            return int(p['table_no'])
        except ValueError:
            return None
    return None


