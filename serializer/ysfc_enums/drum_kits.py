def get_kit_names():
    """Returns list of available drum kit names."""
    return list(DRUM_KITS.keys())


def get_kit_mapping(kit_name):
    """Returns full mapping {note: (wave_no, wave_name)} for a kit."""
    return DRUM_KITS.get(kit_name, {})


def get_wave_for_note(kit_name, note):
    """Returns (wave_no, wave_name) tuple or None."""
    return DRUM_KITS.get(kit_name, {}).get(note)


